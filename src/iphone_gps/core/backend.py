"""Internal backend contracts. No device-library types cross this boundary."""

from typing import Protocol
from .models import Coordinate, Device, Readiness


class Connection(Protocol):
    async def set_location(self, coordinate: Coordinate) -> None: ...
    async def clear_location(self) -> None: ...
    async def wait_disconnected(self) -> None: ...
    async def close(self) -> None: ...


class Backend(Protocol):
    async def list_devices(self) -> list[Device]: ...
    async def check(self, device: Device) -> Readiness: ...
    async def prepare(self, device: Device) -> Readiness: ...
    async def reveal_developer_mode(self, device: Device) -> None: ...
    async def connect(self, device: Device) -> Connection: ...
